-- 7. Do subscribed customers spend more? Compare average speed and total revenue between subscribers and non-subscribers.

SELECT
	subscription_status,
	COUNT(customer_id) as users,
	ROUND(AVG(purchase_amount_usd),2) as avg_revenue,
	ROUND(SUM(purchase_amount_usd),2) as total_revenue
FROM dataset
GROUP BY subscription_status
ORDER BY total_revenue DESC;

/* Business problem: The effectiveness of subscription program is unknown.
Impact:
- Validates subscription model performance.
- Improves customer loyalty programs.
- Increases customer lifetime value (CLV).
*/

-- 8. Top 5 products with highest discount usage %

SELECT 
	item_purchased,
	COUNT(item_purchased) AS total_number_of_times_sold,
	COUNT(CASE WHEN discount_applied = 'Yes' THEN 1 END) AS Number_of_times_sold_when_discount_applied,
	COUNT(CASE WHEN discount_applied = 'Yes' THEN 1 END) * 100.0 / COUNT(*) as discount_percent
FROM dataset
GROUP BY item_purchased
ORDER BY discount_percent DESC;

/* Business problem: Some products may be overly dependent on discounts
Impact:
- Identifies discount driven products
- Helps optimize pricing strategy
- Reduces profit margin loss
*/
 
-- 9. Segment customer into new, returning and loyal based on their total number of previous purchase, and show the count of each segment.

select
	case
		when previous_purchases = '0' then 'New customer'
		when previous_purchases between 1 and 15 then 'Returning customer'
	else 'Loyal customer'
end as customer_segment,
count(*) as customer_count
from dataset
group by customer_segment;

/* Business problem: Lack of customer segmentation leads to generic strategies
Impact:
- Enables personalized marketing
- Improves retention strategies
- Increases conversion rates
*/

-- 10. Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe?
SELECT 
    CASE 
        WHEN previous_purchases > 5 THEN 'Repeat Buyer'
        ELSE 'Normal Buyer'
    END AS customer_type,
    subscription_status,
    COUNT(*) AS total,
    ROUND(
        COUNT(*) * 100.0 
        / SUM(COUNT(*)) OVER (PARTITION BY 
            CASE 
                WHEN previous_purchases > 5 THEN 'Repeat Buyer'
                ELSE 'Normal Buyer'
            END
        ), 2
    ) AS percentage
FROM dataset
GROUP BY customer_type, subscription_status;

/* Business problem: The compant doesn't know top performing products within categories
Impact:
- Improves product placement & recommendations
- Helps inventory optimization
- Increases sales through best seller
*/

-- 11. What are the top 3 most purchased products within each category?

with cte as(
select 
	category,
	item_purchased,
	count(item_purchased) as most_purchased,
	rank() over(partition by category order by count(item_purchased) desc) as rnk
from dataset
group by category, item_purchased
)
select * from cte
where rnk<=3;

/* Business problem: Unclear relationship between loyalty and suubscription
Impact:
- Improves sunscription targeting
- Increases conversion to paid programs
- Increases customer retention streategy
*/

-- 12. What is the revenue contribution of each age group?

select
	case
		when age between 18 and 25 then '18-25'
		when age between 26 and 35 then '26-35'
		when age between 36 and 50 then '36-50'
	else '51+'
	end as age_group,
	round(sum(purchase_amount_usd), 2) as revenue
from dataset
group by age_group
order by revenue desc;

/* Business problem: No visibility into which age group contribution most to revenue
Impact:
- Enables age base targetting
- Enhances marketing efficiency
*/
