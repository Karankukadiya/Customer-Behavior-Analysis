/* Business Questions
*/

-- 1. Which category generates highest revenue?
SELECT
	category,
	sum(purchase_amount_usd) as revenue
FROM dataset
GROUP BY category
ORDER BY revenue DESC;

/* Impacts
- Helps prioritize high-performacing categories
- Optimizes inventory planning
- Improves marketing ROI
*/

-- 2. Are discounts actually increasing purchase value?
SELECT
	discount_applied,
	sum(purchase_amount_usd),
	round(AVG(purchase_amount_usd),2)
FROM dataset
GROUP BY discount_applied;

/* Business problem: Discounts may reduce profit without increasing sales
Impact:
- Identify effectiveness of discounts
- Reduce unnecessary discounts costs
- Improve profit margins
*/

-- 3. What is total revenue generated by male and female customers?
SELECT
	gender,
	sum(purchase_amount_usd) as total_revenue,
	count(customer_id) as total_transactions
FROM dataset
GROUP BY gender
ORDER BY total_revenue DESC;

/* Business problem: Lack of understanding of revenue contribution by gender segments.
Impact:
- Helps design targeted marketing campigns
- Improves customer segmentation strategy
- Enhances personalization efforts
*/

-- 4. Which customer used a discount but still spent more than the average purchase amount?
SELECT
	customer_id,
	purchase_amount_usd,
	discount_applied
FROM dataset
WHERE discount_applied = 'Yes' and purchase_amount_usd > (SELECT AVG(purchase_amount_usd) FROM dataset);

/* Business problem: Company cannot identify high-spending customers who are also discount users.
Impact:
- Identifies premium discount-sensitive customers
- Enables targeted discount campigns
- Improves customer retention and revenue
*/

-- 5. Which are top / bottm 5 products with the highest average review rating.

